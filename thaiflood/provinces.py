_ALIASES = {"กทม": "กรุงเทพมหานคร", "อยุธยา": "พระนครศรีอยุธยา"}
# ชื่อที่เป็นคำทั่วไปด้วย (เช่น "ไม่เลย", "ตากแดด") นับเฉพาะเมื่อมี "จ." หรือ "จังหวัด" นำหน้า
_AMBIGUOUS = {"เลย", "ตาก", "น่าน", "ตรัง", "แพร่"}


def find_provinces(text: str) -> list[str]:
    found: list[str] = []
    for name in PROVINCES + list(_ALIASES):
        canonical = _ALIASES.get(name, name)
        if canonical in found:
            continue
        if name in _AMBIGUOUS:
            hit = any(p + name in text for p in ("จ.", "จ. ", "จังหวัด", "จังหวัด "))
        else:
            hit = name in text
        if hit:
            found.append(canonical)
    return found
